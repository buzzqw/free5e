def translated_term(term: str, notes: str) -> str:
    """Apply the source glossary's usage note where one English form is ambiguous."""
    context = notes.lower()
    contextual = {
        ("make", "a check"): "effettuare una prova",
        ("reduce", "a target to x hp"): "ridurre un bersaglio a x PF",
        ("reaction", "use your reaction to"): "usare la propria reazione per",
        ("ready", "an action"): "Prepararsi",
        ("score", "a critical hit"): "mettere a segno un colpo critico",
        ("take", "an action"): "effettuare un'azione",
        ("take", "an attack"): "effettuare un attacco",
        ("take", "damage"): "subire danni",
        ("use", "a feature to"): "usare una capacità per",
        ("use", "a feature"): "usare una capacità",
        ("use", "a spell slot"): "spendere uno slot incantesimo",
        ("use", "an action to"): "usare un'azione per",
        ("use", "an action"): "usare un'azione",
    }
    return contextual.get((term.lower(), context), TRANSLATIONS.get(term.lower(), "DA APPROVARE: " + term))


def prepare_glossary() -> None:
    TARGET_DIR.mkdir(exist_ok=True)
    with SOURCE_GLOSSARY.open(encoding="utf-8", newline="") as source:
        rows = csv.DictReader(source)
        output = []
        for row in rows:
            term = row["Term"]
            key = term.lower()
            translation = translated_term(term, row["Usage & Notes"])
            if key not in TRANSLATIONS:
                status = "da approvare"
                source_name = "non ancora mappato"
            elif key in APPROVED_CUSTOM_TERMS:
                status = "approvato"
                source_name = "Free5e / termine non attestato nel PDF"
            else:
                status = "base SRD"
                source_name = "IT_SRD_CC_v5.2.1.pdf"
            output.append(
                {
                    "Term": term,
                    "Usage & Notes": row["Usage & Notes"],
                    "it-IT": translation,
                    "Source": source_name,
                    "Status": status,
                }
            )

    with (TARGET_DIR / "glossary.csv").open("w", encoding="utf-8", newline="") as target:
        writer = csv.DictWriter(
            target,
            fieldnames=["Term", "Usage & Notes", "it-IT", "Source", "Status"],
        )
        writer.writeheader()
        writer.writerows(output)


def prepare_status() -> None:
    books = {
        "Characters_Codex": "Character's Codex",
        "Monstrous_Manuscript": "Monstrous Manuscript",
        "Conductors_Companion": "Conductor's Companion",
        "Migration_Guide": "5e to Free5e Migration Guide",
    }
    source_root = ROOT / "en-US"
    rows = []
    for source_path in sorted(source_root.rglob("*.md")):
        relative = source_path.relative_to(source_root)
        book_key = relative.parts[0]
        if book_key not in books:
            continue
        rows.append(
            {
                "Book": books[book_key],
                "Source": "en-US/" + relative.as_posix(),
                "Target": "it-IT/" + relative.as_posix(),
                "Status": "non iniziato",
                "Notes": "",
            }
        )

    with (TARGET_DIR / "translation_status.csv").open(
        "w", encoding="utf-8", newline=""
    ) as target:
        writer = csv.DictWriter(
            target,
            fieldnames=["Book", "Source", "Target", "Status", "Notes"],
        )
        writer.writeheader()
        writer.writerows(rows)


if __name__ == "__main__":
    prepare_glossary()
    prepare_status()
